#ifndef OPENCL_RCD_KERNELS_H
#define OPENCL_RCD_KERNELS_H

static const char* s_rcd_kernel_src =
"#define BAYER_R 0\n"
"#define BAYER_G 1\n"
"#define BAYER_B 2\n"
"#define SQR(x) ((x) * (x))\n"
"\n"
"inline int rcd_get_color(int x, int y, int cfa) {\n"
"    int r = y & 1;\n"
"    int c = x & 1;\n"
"    if (cfa == 0x01000201) { /* GBRG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_B) : ((c == 0) ? BAYER_R : BAYER_G);\n"
"    } else if (cfa == 0x00010102) { /* BGGR */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_B : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_R);\n"
"    } else if (cfa == 0x01020001) { /* GRBG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_R) : ((c == 0) ? BAYER_B : BAYER_G);\n"
"    } else { /* RGGB 0x02010100 or default */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_R : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_B);\n"
"    }\n"
"}\n"
"\n"
"inline float rcd_sample(__global const ushort* raw, int x, int y, int w, int h) {\n"
"    x = clamp(x, 0, w - 1);\n"
"    y = clamp(y, 0, h - 1);\n"
"    return (float)raw[y * w + x];\n"
"}\n"
"\n"
"inline float rcd_sample_buf(__global const float* buf, int x, int y, int w, int h) {\n"
"    x = clamp(x, 0, w - 1);\n"
"    y = clamp(y, 0, h - 1);\n"
"    return buf[y * w + x];\n"
"}\n"
"\n"
"/* Step 1 & 2: Calculate VH discrimination and LPF, interpolate Green at R and B sites */\n"
"__kernel void k_rcd_step1_green(\n"
"    __global const ushort* raw,\n"
"    __global float* green_out,\n"
"    __global float* vh_dir_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int color = rcd_get_color(x, y, cfa);\n"
"    float c_val = rcd_sample(raw, x, y, width, height);\n"
"\n"
"    /* Compute Vertical and Horizontal High-Pass Filter */\n"
"    float v_diff = (rcd_sample(raw, x, y - 3, width, height) - rcd_sample(raw, x, y - 1, width, height) - rcd_sample(raw, x, y + 1, width, height) + rcd_sample(raw, x, y + 3, width, height)) - 3.0f * (rcd_sample(raw, x, y - 2, width, height) + rcd_sample(raw, x, y + 2, width, height)) + 6.0f * c_val;\n"
"    float h_diff = (rcd_sample(raw, x - 3, y, width, height) - rcd_sample(raw, x - 1, y, width, height) - rcd_sample(raw, x + 1, y, width, height) + rcd_sample(raw, x + 3, y, width, height)) - 3.0f * (rcd_sample(raw, x - 2, y, width, height) + rcd_sample(raw, x + 2, y, width, height)) + 6.0f * c_val;\n"
"\n"
"    float v_stat = fmax(1e-8f, SQR(v_diff));\n"
"    float h_stat = fmax(1e-8f, SQR(h_diff));\n"
"    float vh = v_stat / (v_stat + h_stat);\n"
"    vh_dir_out[y * width + x] = vh;\n"
"\n"
"    if (color == BAYER_G) {\n"
"        green_out[y * width + x] = c_val;\n"
"        return;\n"
"    }\n"
"\n"
"    /* Low pass filter at R or B site */\n"
"    float lpfi = c_val + 0.5f * (rcd_sample(raw, x, y - 1, width, height) + rcd_sample(raw, x, y + 1, width, height) + rcd_sample(raw, x - 1, y, width, height) + rcd_sample(raw, x + 1, y, width, height))\n"
"                       + 0.25f * (rcd_sample(raw, x - 1, y - 1, width, height) + rcd_sample(raw, x + 1, y - 1, width, height) + rcd_sample(raw, x - 1, y + 1, width, height) + rcd_sample(raw, x + 1, y + 1, width, height));\n"
"\n"
"    float eps = 1e-4f;\n"
"    float n_grad = eps + fabs(rcd_sample(raw, x, y - 1, width, height) - rcd_sample(raw, x, y + 1, width, height)) + fabs(c_val - rcd_sample(raw, x, y - 2, width, height))\n"
"                       + fabs(rcd_sample(raw, x, y - 1, width, height) - rcd_sample(raw, x, y - 3, width, height)) + fabs(rcd_sample(raw, x, y - 2, width, height) - rcd_sample(raw, x, y - 4, width, height));\n"
"    float s_grad = eps + fabs(rcd_sample(raw, x, y - 1, width, height) - rcd_sample(raw, x, y + 1, width, height)) + fabs(c_val - rcd_sample(raw, x, y + 2, width, height))\n"
"                       + fabs(rcd_sample(raw, x, y + 1, width, height) - rcd_sample(raw, x, y + 3, width, height)) + fabs(rcd_sample(raw, x, y + 2, width, height) - rcd_sample(raw, x, y + 4, width, height));\n"
"    float w_grad = eps + fabs(rcd_sample(raw, x - 1, y, width, height) - rcd_sample(raw, x + 1, y, width, height)) + fabs(c_val - rcd_sample(raw, x - 2, y, width, height))\n"
"                       + fabs(rcd_sample(raw, x - 1, y, width, height) - rcd_sample(raw, x - 3, y, width, height)) + fabs(rcd_sample(raw, x - 2, y, width, height) - rcd_sample(raw, x - 4, y, width, height));\n"
"    float e_grad = eps + fabs(rcd_sample(raw, x - 1, y, width, height) - rcd_sample(raw, x + 1, y, width, height)) + fabs(c_val - rcd_sample(raw, x + 2, y, width, height))\n"
"                       + fabs(rcd_sample(raw, x + 1, y, width, height) - rcd_sample(raw, x + 3, y, width, height)) + fabs(rcd_sample(raw, x + 2, y, width, height) - rcd_sample(raw, x + 4, y, width, height));\n"
"\n"
"    float lpf_n = rcd_sample(raw, x, y - 1, width, height) + 0.5f * (c_val + rcd_sample(raw, x, y - 2, width, height) + rcd_sample(raw, x - 1, y - 1, width, height) + rcd_sample(raw, x + 1, y - 1, width, height));\n"
"    float lpf_s = rcd_sample(raw, x, y + 1, width, height) + 0.5f * (c_val + rcd_sample(raw, x, y + 2, width, height) + rcd_sample(raw, x - 1, y + 1, width, height) + rcd_sample(raw, x + 1, y + 1, width, height));\n"
"    float lpf_w = rcd_sample(raw, x - 1, y, width, height) + 0.5f * (c_val + rcd_sample(raw, x - 2, y, width, height) + rcd_sample(raw, x - 1, y - 1, width, height) + rcd_sample(raw, x - 1, y + 1, width, height));\n"
"    float lpf_e = rcd_sample(raw, x + 1, y, width, height) + 0.5f * (c_val + rcd_sample(raw, x + 2, y, width, height) + rcd_sample(raw, x + 1, y - 1, width, height) + rcd_sample(raw, x + 1, y + 1, width, height));\n"
"\n"
"    float n_est = rcd_sample(raw, x, y - 1, width, height) * (2.0f * lpfi) / (eps + lpfi + lpf_n);\n"
"    float s_est = rcd_sample(raw, x, y + 1, width, height) * (2.0f * lpfi) / (eps + lpfi + lpf_s);\n"
"    float w_est = rcd_sample(raw, x - 1, y, width, height) * (2.0f * lpfi) / (eps + lpfi + lpf_w);\n"
"    float e_est = rcd_sample(raw, x + 1, y, width, height) * (2.0f * lpfi) / (eps + lpfi + lpf_e);\n"
"\n"
"    float v_est = (s_grad * n_est + n_grad * s_est) / (n_grad + s_grad);\n"
"    float h_est = (w_grad * e_est + e_grad * w_est) / (e_grad + w_grad);\n"
"\n"
"    /* Adaptive horizontal/vertical discrimination */\n"
"    green_out[y * width + x] = vh * h_est + (1.0f - vh) * v_est;\n"
"}\n"
"\n"
"/* Step 2: Full RGB Reconstruction with Ratio Corrected Color Differences */\n"
"__kernel void k_rcd_step2_rgb(\n"
"    __global const ushort* raw,\n"
"    __global const float* green,\n"
"    __global const float* vh_dir,\n"
"    __global ushort* rgb_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int color = rcd_get_color(x, y, cfa);\n"
"    float g_val = green[y * width + x];\n"
"    float r_val = 0.0f, b_val = 0.0f;\n"
"    float eps = 1e-4f;\n"
"\n"
"    if (color == BAYER_R) {\n"
"        r_val = (float)raw[y * width + x];\n"
"        /* Diagonal Blue estimation */\n"
"        float b_nw = rcd_sample(raw, x - 1, y - 1, width, height);\n"
"        float b_ne = rcd_sample(raw, x + 1, y - 1, width, height);\n"
"        float b_sw = rcd_sample(raw, x - 1, y + 1, width, height);\n"
"        float b_se = rcd_sample(raw, x + 1, y + 1, width, height);\n"
"\n"
"        float g_nw = rcd_sample_buf(green, x - 1, y - 1, width, height);\n"
"        float g_ne = rcd_sample_buf(green, x + 1, y - 1, width, height);\n"
"        float g_sw = rcd_sample_buf(green, x - 1, y + 1, width, height);\n"
"        float g_se = rcd_sample_buf(green, x + 1, y + 1, width, height);\n"
"\n"
"        float d1 = fabs((b_nw - g_nw) - (b_se - g_se));\n"
"        float d2 = fabs((b_ne - g_ne) - (b_sw - g_sw));\n"
"        float w1 = 1.0f / (d1 * d1 + eps);\n"
"        float w2 = 1.0f / (d2 * d2 + eps);\n"
"        float diff_b = (w1 * 0.5f * ((b_nw - g_nw) + (b_se - g_se)) + w2 * 0.5f * ((b_ne - g_ne) + (b_sw - g_sw))) / (w1 + w2);\n"
"        b_val = g_val + diff_b;\n"
"    } else if (color == BAYER_B) {\n"
"        b_val = (float)raw[y * width + x];\n"
"        /* Diagonal Red estimation */\n"
"        float r_nw = rcd_sample(raw, x - 1, y - 1, width, height);\n"
"        float r_ne = rcd_sample(raw, x + 1, y - 1, width, height);\n"
"        float r_sw = rcd_sample(raw, x - 1, y + 1, width, height);\n"
"        float r_se = rcd_sample(raw, x + 1, y + 1, width, height);\n"
"\n"
"        float g_nw = rcd_sample_buf(green, x - 1, y - 1, width, height);\n"
"        float g_ne = rcd_sample_buf(green, x + 1, y - 1, width, height);\n"
"        float g_sw = rcd_sample_buf(green, x - 1, y + 1, width, height);\n"
"        float g_se = rcd_sample_buf(green, x + 1, y + 1, width, height);\n"
"\n"
"        float d1 = fabs((r_nw - g_nw) - (r_se - g_se));\n"
"        float d2 = fabs((r_ne - g_ne) - (r_sw - g_sw));\n"
"        float w1 = 1.0f / (d1 * d1 + eps);\n"
"        float w2 = 1.0f / (d2 * d2 + eps);\n"
"        float diff_r = (w1 * 0.5f * ((r_nw - g_nw) + (r_se - g_se)) + w2 * 0.5f * ((r_ne - g_ne) + (r_sw - g_sw))) / (w1 + w2);\n"
"        r_val = g_val + diff_r;\n"
"    } else { /* BAYER_G */\n"
"        float vh = vh_dir[y * width + x];\n"
"        int c_left = rcd_get_color(x - 1, y, cfa);\n"
"        float diff_r = 0.0f, diff_b = 0.0f;\n"
"        if (c_left == BAYER_R || rcd_get_color(x + 1, y, cfa) == BAYER_R) {\n"
"            /* R is horizontal, B is vertical */\n"
"            float dr_l = rcd_sample(raw, x - 1, y, width, height) - rcd_sample_buf(green, x - 1, y, width, height);\n"
"            float dr_r = rcd_sample(raw, x + 1, y, width, height) - rcd_sample_buf(green, x + 1, y, width, height);\n"
"            diff_r = 0.5f * (dr_l + dr_r);\n"
"            float db_u = rcd_sample(raw, x, y - 1, width, height) - rcd_sample_buf(green, x, y - 1, width, height);\n"
"            float db_d = rcd_sample(raw, x, y + 1, width, height) - rcd_sample_buf(green, x, y + 1, width, height);\n"
"            diff_b = 0.5f * (db_u + db_d);\n"
"        } else {\n"
"            /* B is horizontal, R is vertical */\n"
"            float db_l = rcd_sample(raw, x - 1, y, width, height) - rcd_sample_buf(green, x - 1, y, width, height);\n"
"            float db_r = rcd_sample(raw, x + 1, y, width, height) - rcd_sample_buf(green, x + 1, y, width, height);\n"
"            diff_b = 0.5f * (db_l + db_r);\n"
"            float dr_u = rcd_sample(raw, x, y - 1, width, height) - rcd_sample_buf(green, x, y - 1, width, height);\n"
"            float dr_d = rcd_sample(raw, x, y + 1, width, height) - rcd_sample_buf(green, x, y + 1, width, height);\n"
"            diff_r = 0.5f * (dr_u + dr_d);\n"
"        }\n"
"        r_val = g_val + diff_r;\n"
"        b_val = g_val + diff_b;\n"
"    }\n"
"\n"
"    int out_idx = (y * width + x) * 3;\n"
"    rgb_out[out_idx + 0] = (ushort)clamp(r_val, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 1] = (ushort)clamp(g_val, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 2] = (ushort)clamp(b_val, 0.0f, 65535.0f);\n"
"}\n";

#endif /* OPENCL_RCD_KERNELS_H */
