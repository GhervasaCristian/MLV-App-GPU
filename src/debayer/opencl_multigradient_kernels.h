#ifndef OPENCL_MULTIGRADIENT_KERNELS_H
#define OPENCL_MULTIGRADIENT_KERNELS_H

static const char* s_multigradient_kernel_src =
"#define BAYER_R 0\n"
"#define BAYER_G 1\n"
"#define BAYER_B 2\n"
"\n"
"inline int mg_get_color(int x, int y, int cfa) {\n"
"    int r = y & 1;\n"
"    int c = x & 1;\n"
"    if (cfa == 0x01000201) { /* GBRG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_B) : ((c == 0) ? BAYER_R : BAYER_G);\n"
"    } else if (cfa == 0x00010102) { /* BGGR */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_B : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_R);\n"
"    } else if (cfa == 0x01020001) { /* GRBG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_R) : ((c == 0) ? BAYER_B : BAYER_G);\n"
"    } else { /* RGGB 0x02010100 or default */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_R : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_B);\n"
"    }\n"
"}\n"
"\n"
"inline float mg_sample_bayer(__global const ushort* raw, int x, int y, int w, int h) {\n"
"    x = (x < 0) ? -x : (x >= w ? 2 * w - 2 - x : x);\n"
"    y = (y < 0) ? -y : (y >= h ? 2 * h - 2 - y : y);\n"
"    return (float)raw[y * w + x];\n"
"}\n"
"\n"
"/* Pass 1: Multi-Gradient Green Interpolation */\n"
"__kernel void k_mg_interpolate_green(\n"
"    __global const ushort* raw,\n"
"    __global float* green_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int color = mg_get_color(x, y, cfa);\n"
"    if (color == BAYER_G) {\n"
"        green_out[y * width + x] = (float)raw[y * width + x];\n"
"        return;\n"
"    }\n"
"\n"
"    /* At R or B site: calculate horizontal and vertical gradients with 2nd order Laplacian */\n"
"    float c_center = (float)raw[y * width + x];\n"
"    float g_l = mg_sample_bayer(raw, x - 1, y, width, height);\n"
"    float g_r = mg_sample_bayer(raw, x + 1, y, width, height);\n"
"    float g_u = mg_sample_bayer(raw, x, y - 1, width, height);\n"
"    float g_d = mg_sample_bayer(raw, x, y + 1, width, height);\n"
"\n"
"    float c_l2 = mg_sample_bayer(raw, x - 2, y, width, height);\n"
"    float c_r2 = mg_sample_bayer(raw, x + 2, y, width, height);\n"
"    float c_u2 = mg_sample_bayer(raw, x, y - 2, width, height);\n"
"    float c_d2 = mg_sample_bayer(raw, x, y + 2, width, height);\n"
"\n"
"    float grad_h = fabs(g_l - g_r) + fabs(2.0f * c_center - c_l2 - c_r2);\n"
"    float grad_v = fabs(g_u - g_d) + fabs(2.0f * c_center - c_u2 - c_d2);\n"
"\n"
"    float est_h = 0.5f * (g_l + g_r) + 0.25f * (2.0f * c_center - c_l2 - c_r2);\n"
"    float est_v = 0.5f * (g_u + g_d) + 0.25f * (2.0f * c_center - c_u2 - c_d2);\n"
"\n"
"    float eps = 1e-4f;\n"
"    float w_h = 1.0f / (grad_h * grad_h + eps);\n"
"    float w_v = 1.0f / (grad_v * grad_v + eps);\n"
"\n"
"    green_out[y * width + x] = (w_h * est_h + w_v * est_v) / (w_h + w_v);\n"
"}\n"
"\n"
"/* Pass 2: Color Differences & Full RGB Reconstruction */\n"
"inline float mg_sample_green(__global const float* g, int x, int y, int w, int h) {\n"
"    x = clamp(x, 0, w - 1);\n"
"    y = clamp(y, 0, h - 1);\n"
"    return g[y * w + x];\n"
"}\n"
"\n"
"__kernel void k_mg_reconstruct_rgb(\n"
"    __global const ushort* raw,\n"
"    __global const float* green,\n"
"    __global ushort* rgb_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    float g_val = green[y * width + x];\n"
"    float r_val = 0.0f, b_val = 0.0f;\n"
"    int color = mg_get_color(x, y, cfa);\n"
"\n"
"    if (color == BAYER_R) {\n"
"        r_val = (float)raw[y * width + x];\n"
"        /* Diagonal blue neighbors */\n"
"        float db_nw = mg_sample_bayer(raw, x-1, y-1, width, height) - mg_sample_green(green, x-1, y-1, width, height);\n"
"        float db_ne = mg_sample_bayer(raw, x+1, y-1, width, height) - mg_sample_green(green, x+1, y-1, width, height);\n"
"        float db_sw = mg_sample_bayer(raw, x-1, y+1, width, height) - mg_sample_green(green, x-1, y+1, width, height);\n"
"        float db_se = mg_sample_bayer(raw, x+1, y+1, width, height) - mg_sample_green(green, x+1, y+1, width, height);\n"
"\n"
"        float d1 = fabs(db_nw - db_se);\n"
"        float d2 = fabs(db_ne - db_sw);\n"
"        float w1 = 1.0f / (d1 * d1 + 1e-4f);\n"
"        float w2 = 1.0f / (d2 * d2 + 1e-4f);\n"
"        float diff_b = (w1 * (db_nw + db_se) * 0.5f + w2 * (db_ne + db_sw) * 0.5f) / (w1 + w2);\n"
"        b_val = g_val + diff_b;\n"
"    } else if (color == BAYER_B) {\n"
"        b_val = (float)raw[y * width + x];\n"
"        /* Diagonal red neighbors */\n"
"        float dr_nw = mg_sample_bayer(raw, x-1, y-1, width, height) - mg_sample_green(green, x-1, y-1, width, height);\n"
"        float dr_ne = mg_sample_bayer(raw, x+1, y-1, width, height) - mg_sample_green(green, x+1, y-1, width, height);\n"
"        float dr_sw = mg_sample_bayer(raw, x-1, y+1, width, height) - mg_sample_green(green, x-1, y+1, width, height);\n"
"        float dr_se = mg_sample_bayer(raw, x+1, y+1, width, height) - mg_sample_green(green, x+1, y+1, width, height);\n"
"\n"
"        float d1 = fabs(dr_nw - dr_se);\n"
"        float d2 = fabs(dr_ne - dr_sw);\n"
"        float w1 = 1.0f / (d1 * d1 + 1e-4f);\n"
"        float w2 = 1.0f / (d2 * d2 + 1e-4f);\n"
"        float diff_r = (w1 * (dr_nw + dr_se) * 0.5f + w2 * (dr_ne + dr_sw) * 0.5f) / (w1 + w2);\n"
"        r_val = g_val + diff_r;\n"
"    } else { /* BAYER_G */\n"
"        int c_left = mg_get_color(x - 1, y, cfa);\n"
"        float diff_r = 0.0f, diff_b = 0.0f;\n"
"        if (c_left == BAYER_R || mg_get_color(x + 1, y, cfa) == BAYER_R) {\n"
"            float dr_l = mg_sample_bayer(raw, x-1, y, width, height) - mg_sample_green(green, x-1, y, width, height);\n"
"            float dr_r = mg_sample_bayer(raw, x+1, y, width, height) - mg_sample_green(green, x+1, y, width, height);\n"
"            diff_r = 0.5f * (dr_l + dr_r);\n"
"            float db_u = mg_sample_bayer(raw, x, y-1, width, height) - mg_sample_green(green, x, y-1, width, height);\n"
"            float db_d = mg_sample_bayer(raw, x, y+1, width, height) - mg_sample_green(green, x, y+1, width, height);\n"
"            diff_b = 0.5f * (db_u + db_d);\n"
"        } else {\n"
"            float db_l = mg_sample_bayer(raw, x-1, y, width, height) - mg_sample_green(green, x-1, y, width, height);\n"
"            float db_r = mg_sample_bayer(raw, x+1, y, width, height) - mg_sample_green(green, x+1, y, width, height);\n"
"            diff_b = 0.5f * (db_l + db_r);\n"
"            float dr_u = mg_sample_bayer(raw, x, y-1, width, height) - mg_sample_green(green, x, y-1, width, height);\n"
"            float dr_d = mg_sample_bayer(raw, x, y+1, width, height) - mg_sample_green(green, x, y+1, width, height);\n"
"            diff_r = 0.5f * (dr_u + dr_d);\n"
"        }\n"
"        r_val = g_val + diff_r;\n"
"        b_val = g_val + diff_b;\n"
"    }\n"
"\n"
"    int out_idx = (y * width + x) * 3;\n"
"    rgb_out[out_idx + 0] = (ushort)clamp(r_val, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 1] = (ushort)clamp(g_val, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 2] = (ushort)clamp(b_val, 0.0f, 65535.0f);\n"
"}\n";

#endif /* OPENCL_MULTIGRADIENT_KERNELS_H */
