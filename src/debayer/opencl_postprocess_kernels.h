#ifndef OPENCL_POSTPROCESS_KERNELS_H
#define OPENCL_POSTPROCESS_KERNELS_H

/* OpenCL Kernel for Zero-Copy GPU Post-Processing:
 * - 3x3 Color Matrix & White Balance & Exposure Gain
 * - 1D Tone Curve / Gamma Transfer Function
 * - Directional 2D Luma Sharpening (100% Crispness without chroma fringing)
 * - Direct 8-bit RGB888 Display Packing (or 16-bit for export)
 */

static const char *s_opencl_postprocess_source =
"#define CLAMP16(v) ((v) < 0.0f ? 0.0f : ((v) > 65535.0f ? 65535.0f : (v)))\n"
"#define CLAMP8(v)  ((v) < 0 ? 0 : ((v) > 255 ? 255 : (v)))\n"
"\n"
"__kernel void k_postprocess_frame(\n"
"    __global const ushort *in_rgb,       /* [H, W, 3] from debayer */\n"
"    __global uchar *out_rgb8,            /* [H, W, 3] 8-bit display output (if != NULL) */\n"
"    __global ushort *out_rgb16,          /* [H, W, 3] 16-bit output (if != NULL) */\n"
"    int width,\n"
"    int height,\n"
"    __constant float *matrix,            /* 3x3 matrix: mat[0..8] */\n"
"    float exposure_gain,                 /* linear exposure multiplier */\n"
"    __global const ushort *tone_lut,     /* 65536-entry 16-bit tone/gamma LUT (optional) */\n"
"    float sharpen_strength,              /* 0.0 to 1.0 (1.0 = 100%) */\n"
"    int has_tone_lut\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int idx = (y * width + x) * 3;\n"
"    float r = (float)in_rgb[idx + 0];\n"
"    float g = (float)in_rgb[idx + 1];\n"
"    float b = (float)in_rgb[idx + 2];\n"
"\n"
"    /* 1. Matrix multiplication & exposure */\n"
"    float r_mat = (matrix[0] * r + matrix[1] * g + matrix[2] * b) * exposure_gain;\n"
"    float g_mat = (matrix[3] * r + matrix[4] * g + matrix[5] * b) * exposure_gain;\n"
"    float b_mat = (matrix[6] * r + matrix[7] * g + matrix[8] * b) * exposure_gain;\n"
"\n"
"    r_mat = CLAMP16(r_mat);\n"
"    g_mat = CLAMP16(g_mat);\n"
"    b_mat = CLAMP16(b_mat);\n"
"\n"
"    /* 2. Tone Curve LUT mapping (if provided) */\n"
"    if (has_tone_lut && tone_lut != 0) {\n"
"        int ir = (int)r_mat;\n"
"        int ig = (int)g_mat;\n"
"        int ib = (int)b_mat;\n"
"        ir = (ir < 0) ? 0 : ((ir > 65535) ? 65535 : ir);\n"
"        ig = (ig < 0) ? 0 : ((ig > 65535) ? 65535 : ig);\n"
"        ib = (ib < 0) ? 0 : ((ib > 65535) ? 65535 : ib);\n"
"        r_mat = (float)tone_lut[ir];\n"
"        g_mat = (float)tone_lut[ig];\n"
"        b_mat = (float)tone_lut[ib];\n"
"    }\n"
"\n"
"    /* 3. 2D Luma Sharpening */\n"
"    if (sharpen_strength > 0.005f && x > 0 && x < width - 1 && y > 0 && y < height - 1) {\n"
"        /* Convert center to YCbCr */\n"
"        float Y = 0.299f * r_mat + 0.587f * g_mat + 0.114f * b_mat;\n"
"        float Cb = -0.168736f * r_mat - 0.331264f * g_mat + 0.5f * b_mat;\n"
"        float Cr = 0.5f * r_mat - 0.418688f * g_mat - 0.081312f * b_mat;\n"
"\n"
"        /* Sample 4 cross neighbors */\n"
"        int idx_top = ((y - 1) * width + x) * 3;\n"
"        int idx_bot = ((y + 1) * width + x) * 3;\n"
"        int idx_lft = (y * width + (x - 1)) * 3;\n"
"        int idx_rgt = (y * width + (x + 1)) * 3;\n"
"\n"
"        float Y_t = 0.299f * (float)in_rgb[idx_top] + 0.587f * (float)in_rgb[idx_top+1] + 0.114f * (float)in_rgb[idx_top+2];\n"
"        float Y_b = 0.299f * (float)in_rgb[idx_bot] + 0.587f * (float)in_rgb[idx_bot+1] + 0.114f * (float)in_rgb[idx_bot+2];\n"
"        float Y_l = 0.299f * (float)in_rgb[idx_lft] + 0.587f * (float)in_rgb[idx_lft+1] + 0.114f * (float)in_rgb[idx_lft+2];\n"
"        float Y_r = 0.299f * (float)in_rgb[idx_rgt] + 0.587f * (float)in_rgb[idx_rgt+1] + 0.114f * (float)in_rgb[idx_rgt+2];\n"
"\n"
"        /* High-pass Laplacian filter */\n"
"        float laplacian = 4.0f * Y - (Y_t + Y_b + Y_l + Y_r);\n"
"        float Y_sharp = CLAMP16(Y + sharpen_strength * laplacian);\n"
"\n"
"        /* Reconstruct RGB from sharpened Luma & Chroma */\n"
"        r_mat = CLAMP16(Y_sharp + 1.402f * Cr);\n"
"        g_mat = CLAMP16(Y_sharp - 0.344136f * Cb - 0.714136f * Cr);\n"
"        b_mat = CLAMP16(Y_sharp + 1.772f * Cb);\n"
"    }\n"
"\n"
"    /* 4. Output write */\n"
"    if (out_rgb8 != 0) {\n"
"        /* 8-bit RGB display output (shifted down by 8 bits with rounding) */\n"
"        int r8 = (int)(r_mat * (255.0f / 65535.0f) + 0.5f);\n"
"        int g8 = (int)(g_mat * (255.0f / 65535.0f) + 0.5f);\n"
"        int b8 = (int)(b_mat * (255.0f / 65535.0f) + 0.5f);\n"
"        out_rgb8[idx + 0] = (uchar)CLAMP8(r8);\n"
"        out_rgb8[idx + 1] = (uchar)CLAMP8(g8);\n"
"        out_rgb8[idx + 2] = (uchar)CLAMP8(b8);\n"
"    }\n"
"    if (out_rgb16 != 0) {\n"
"        out_rgb16[idx + 0] = (ushort)r_mat;\n"
"        out_rgb16[idx + 1] = (ushort)g_mat;\n"
"        out_rgb16[idx + 2] = (ushort)b_mat;\n"
"    }\n"
"}\n";

#endif /* OPENCL_POSTPROCESS_KERNELS_H */
