#ifndef OPENCL_MULTIGRADIENT_KERNELS_H
#define OPENCL_MULTIGRADIENT_KERNELS_H

static const char* s_multigradient_kernel_src =
"#define BAYER_R 0\n"
"#define BAYER_G 1\n"
"#define BAYER_B 2\n"
"\n"
"inline int mg_get_color(int x, int y, int cfa) {\n"
"    int r = y & 1;\n"
"    int c = x & 1;\n"
"    if (cfa == 0x01000201) { /* GBRG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_B) : ((c == 0) ? BAYER_R : BAYER_G);\n"
"    } else if (cfa == 0x00010102) { /* BGGR */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_B : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_R);\n"
"    } else if (cfa == 0x01020001) { /* GRBG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_R) : ((c == 0) ? BAYER_B : BAYER_G);\n"
"    } else { /* RGGB 0x02010100 or default */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_R : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_B);\n"
"    }\n"
"}\n"
"\n"
"inline float mg_sample_bayer(__global const ushort* raw, int x, int y, int w, int h) {\n"
"    x = clamp(x, 0, w - 1);\n"
"    y = clamp(y, 0, h - 1);\n"
"    return (float)raw[y * w + x];\n"
"}\n"
"\n"
"/* Ultra-Fast Single-Pass Debayer for high frame rate playback */\n"
"__kernel void k_mg_fast_single_pass(\n"
"    __global const ushort* raw,\n"
"    __global ushort* rgb_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int color = mg_get_color(x, y, cfa);\n"
"    float r_val, g_val, b_val;\n"
"\n"
"    if (color == BAYER_G) {\n"
"        g_val = (float)raw[y * width + x];\n"
"        int c_left = mg_get_color(x - 1, y, cfa);\n"
"        if (c_left == BAYER_R || mg_get_color(x + 1, y, cfa) == BAYER_R) {\n"
"            r_val = 0.5f * (mg_sample_bayer(raw, x - 1, y, width, height) + mg_sample_bayer(raw, x + 1, y, width, height));\n"
"            b_val = 0.5f * (mg_sample_bayer(raw, x, y - 1, width, height) + mg_sample_bayer(raw, x, y + 1, width, height));\n"
"        } else {\n"
"            b_val = 0.5f * (mg_sample_bayer(raw, x - 1, y, width, height) + mg_sample_bayer(raw, x + 1, y, width, height));\n"
"            r_val = 0.5f * (mg_sample_bayer(raw, x, y - 1, width, height) + mg_sample_bayer(raw, x, y + 1, width, height));\n"
"        }\n"
"    } else if (color == BAYER_R) {\n"
"        r_val = (float)raw[y * width + x];\n"
"        g_val = 0.25f * (mg_sample_bayer(raw, x - 1, y, width, height) + mg_sample_bayer(raw, x + 1, y, width, height) +\n"
"                         mg_sample_bayer(raw, x, y - 1, width, height) + mg_sample_bayer(raw, x, y + 1, width, height));\n"
"        b_val = 0.25f * (mg_sample_bayer(raw, x - 1, y - 1, width, height) + mg_sample_bayer(raw, x + 1, y - 1, width, height) +\n"
"                         mg_sample_bayer(raw, x - 1, y + 1, width, height) + mg_sample_bayer(raw, x + 1, y + 1, width, height));\n"
"    } else { /* BAYER_B */\n"
"        b_val = (float)raw[y * width + x];\n"
"        g_val = 0.25f * (mg_sample_bayer(raw, x - 1, y, width, height) + mg_sample_bayer(raw, x + 1, y, width, height) +\n"
"                         mg_sample_bayer(raw, x, y - 1, width, height) + mg_sample_bayer(raw, x, y + 1, width, height));\n"
"        r_val = 0.25f * (mg_sample_bayer(raw, x - 1, y - 1, width, height) + mg_sample_bayer(raw, x + 1, y - 1, width, height) +\n"
"                         mg_sample_bayer(raw, x - 1, y + 1, width, height) + mg_sample_bayer(raw, x + 1, y + 1, width, height));\n"
"    }\n"
"\n"
"    int out_idx = (y * width + x) * 3;\n"
"    rgb_out[out_idx + 0] = (ushort)clamp(r_val, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 1] = (ushort)clamp(g_val, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 2] = (ushort)clamp(b_val, 0.0f, 65535.0f);\n"
"}\n";

#endif /* OPENCL_MULTIGRADIENT_KERNELS_H */
