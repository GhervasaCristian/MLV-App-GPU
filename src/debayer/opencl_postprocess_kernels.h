#ifndef OPENCL_POSTPROCESS_KERNELS_H
#define OPENCL_POSTPROCESS_KERNELS_H

/* OpenCL Kernel for Zero-Copy GPU Post-Processing:
 * - Black / White level normalization via 65536-entry levels_lut (pre_calc_levels)
 * - 3x3 Color Matrix & White Balance & Exposure (proper_wb_matrix * wb_exposure)
 * - Reference Reinhard Gamut Compression (exact match to MLV-App raw_processing.c)
 * - Transfer Function / Display Gamma curve mapping via 65536-entry gamma_lut (pre_calc_gamma)
 * - Directional 2D Luma Sharpening in YCbCr space (100% Crispness without chroma fringing)
 * - Direct 8-bit RGB888 Display Packing (or 16-bit for export)
 */

static const char *s_opencl_postprocess_source =
"#define CLAMP16(v) ((v) < 0.0f ? 0.0f : ((v) > 65535.0f ? 65535.0f : (v)))\n"
"#define CLAMP8(v)  ((v) < 0 ? 0 : ((v) > 255 ? 255 : (v)))\n"
"\n"
"inline float ocl_reinhard(float x) { return (x < 0.0f) ? x : (x / (1.0f + x)); }\n"
"inline float ocl_reinhard_color(float x) { return (x < 0.5f) ? x : (ocl_reinhard((x - 0.5f) / 0.5f) * 0.5f + 0.5f); }\n"
"inline float ocl_reinhard_blue(float x) { return (x < 0.7f) ? x : (ocl_reinhard((x - 0.7f) / 0.3f) * 0.3f + 0.7f); }\n"
"\n"
"__kernel void k_postprocess_frame(\n"
"    __global const ushort *in_rgb,       /* [H, W, 3] from debayer (16-bit sensor scale) */\n"
"    __global uchar *out_rgb8,            /* [H, W, 3] 8-bit display output (if != NULL) */\n"
"    __global ushort *out_rgb16,          /* [H, W, 3] 16-bit output (if != NULL) */\n"
"    int width,\n"
"    int height,\n"
"    __constant float *matrix,            /* 3x3 combined matrix (proper_wb_matrix * wb_exposure) */\n"
"    __global const ushort *levels_lut,   /* 65536-entry pre_calc_levels LUT */\n"
"    __global const ushort *gamma_lut,    /* 65536-entry pre_calc_gamma LUT */\n"
"    float sharpen_strength,              /* 0.0 to 1.0 (1.0 = 100%) */\n"
"    float y_r, float y_g, float y_b     /* Gamut compression luma weights */\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int idx = (y * width + x) * 3;\n"
"    ushort raw_r = in_rgb[idx + 0];\n"
"    ushort raw_g = in_rgb[idx + 1];\n"
"    ushort raw_b = in_rgb[idx + 2];\n"
"\n"
"    /* 1. Black/White level normalization via pre_calc_levels */\n"
"    float r_norm = (levels_lut != 0) ? (float)levels_lut[raw_r] : (float)raw_r;\n"
"    float g_norm = (levels_lut != 0) ? (float)levels_lut[raw_g] : (float)raw_g;\n"
"    float b_norm = (levels_lut != 0) ? (float)levels_lut[raw_b] : (float)raw_b;\n"
"\n"
"    /* 2. 3x3 Color Matrix & White Balance & Exposure */\n"
"    float r_mat = matrix[0] * r_norm + matrix[1] * g_norm + matrix[2] * b_norm;\n"
"    float g_mat = matrix[3] * r_norm + matrix[4] * g_norm + matrix[5] * b_norm;\n"
"    float b_mat = matrix[6] * r_norm + matrix[7] * g_norm + matrix[8] * b_norm;\n"
"\n"
"    /* 3. Reference Gamut compression (identical to raw_processing.c) */\n"
"    float Y_cam = y_r * r_mat + y_g * g_mat + y_b * b_mat;\n"
"    if (Y_cam > 0.0f) {\n"
"        float min_channel = fmin(fmin(r_mat, g_mat), b_mat);\n"
"        float tm_r = ocl_reinhard_color((Y_cam - r_mat) / Y_cam);\n"
"        float tm_g = ocl_reinhard((Y_cam - g_mat) / Y_cam);\n"
"        float tm_b = ocl_reinhard_blue((Y_cam - b_mat) / Y_cam);\n"
"        float r2 = -(tm_r * Y_cam) + Y_cam;\n"
"        float g2 = -(tm_g * Y_cam) + Y_cam;\n"
"        float b2 = -(tm_b * Y_cam) + Y_cam;\n"
"        float min_r2 = fmin(fmin(r2, g2), b2);\n"
"        float denom = Y_cam - min_channel;\n"
"        float desaturate_factor = (denom > 1e-4f) ? ((Y_cam - min_r2) / denom) : 1.0f;\n"
"        r_mat = (r_mat - Y_cam) * desaturate_factor + Y_cam;\n"
"        g_mat = (g_mat - Y_cam) * desaturate_factor + Y_cam;\n"
"        b_mat = (b_mat - Y_cam) * desaturate_factor + Y_cam;\n"
"    }\n"
"\n"
"    /* 4. Tone / Gamma transfer curve mapping via pre_calc_gamma */\n"
"    float r_out, g_out, b_out;\n"
"    if (gamma_lut != 0) {\n"
"        int ir = clamp((int)r_mat, 0, 65535);\n"
"        int ig = clamp((int)g_mat, 0, 65535);\n"
"        int ib = clamp((int)b_mat, 0, 65535);\n"
"        r_out = (float)gamma_lut[ir];\n"
"        g_out = (float)gamma_lut[ig];\n"
"        b_out = (float)gamma_lut[ib];\n"
"    } else {\n"
"        r_out = CLAMP16(r_mat);\n"
"        g_out = CLAMP16(g_mat);\n"
"        b_out = CLAMP16(b_mat);\n"
"    }\n"
"\n"
"    /* 5. 2D Luma Sharpening in YCbCr space */\n"
"    if (sharpen_strength > 0.005f && x > 0 && x < width - 1 && y > 0 && y < height - 1) {\n"
"        float Y  =  0.299f    * r_out + 0.587f    * g_out + 0.114f    * b_out;\n"
"        float Cb = -0.168736f * r_out - 0.331264f * g_out + 0.5f      * b_out;\n"
"        float Cr =  0.5f      * r_out - 0.418688f * g_out - 0.081312f * b_out;\n"
"\n"
"        int idx_top = ((y - 1) * width + x) * 3;\n"
"        int idx_bot = ((y + 1) * width + x) * 3;\n"
"        int idx_lft = (y * width + (x - 1)) * 3;\n"
"        int idx_rgt = (y * width + (x + 1)) * 3;\n"
"\n"
"        float Y_t = 0.299f * (float)levels_lut[in_rgb[idx_top]]   + 0.587f * (float)levels_lut[in_rgb[idx_top+1]] + 0.114f * (float)levels_lut[in_rgb[idx_top+2]];\n"
"        float Y_b = 0.299f * (float)levels_lut[in_rgb[idx_bot]]   + 0.587f * (float)levels_lut[in_rgb[idx_bot+1]] + 0.114f * (float)levels_lut[in_rgb[idx_bot+2]];\n"
"        float Y_l = 0.299f * (float)levels_lut[in_rgb[idx_lft]]   + 0.587f * (float)levels_lut[in_rgb[idx_lft+1]] + 0.114f * (float)levels_lut[in_rgb[idx_lft+2]];\n"
"        float Y_r = 0.299f * (float)levels_lut[in_rgb[idx_rgt]]   + 0.587f * (float)levels_lut[in_rgb[idx_rgt+1]] + 0.114f * (float)levels_lut[in_rgb[idx_rgt+2]];\n"
"        float Y_c = 0.299f * r_norm + 0.587f * g_norm + 0.114f * b_norm;\n"
"\n"
"        float laplacian = 4.0f * Y_c - (Y_t + Y_b + Y_l + Y_r);\n"
"        float Y_sharp = CLAMP16(Y + sharpen_strength * laplacian * 0.8f);\n"
"\n"
"        r_out = CLAMP16(Y_sharp + 1.402f * Cr);\n"
"        g_out = CLAMP16(Y_sharp - 0.344136f * Cb - 0.714136f * Cr);\n"
"        b_out = CLAMP16(Y_sharp + 1.772f * Cb);\n"
"    }\n"
"\n"
"    /* 6. Output packing */\n"
"    if (out_rgb8 != 0) {\n"
"        int r8 = (int)(r_out * (255.0f / 65535.0f) + 0.5f);\n"
"        int g8 = (int)(g_out * (255.0f / 65535.0f) + 0.5f);\n"
"        int b8 = (int)(b_out * (255.0f / 65535.0f) + 0.5f);\n"
"        out_rgb8[idx + 0] = (uchar)CLAMP8(r8);\n"
"        out_rgb8[idx + 1] = (uchar)CLAMP8(g8);\n"
"        out_rgb8[idx + 2] = (uchar)CLAMP8(b8);\n"
"    }\n"
"    if (out_rgb16 != 0) {\n"
"        out_rgb16[idx + 0] = (ushort)r_out;\n"
"        out_rgb16[idx + 1] = (ushort)g_out;\n"
"        out_rgb16[idx + 2] = (ushort)b_out;\n"
"    }\n"
"}\n";

#endif /* OPENCL_POSTPROCESS_KERNELS_H */
