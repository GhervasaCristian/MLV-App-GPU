#ifndef OPENCL_POSTPROCESS_KERNELS_H
#define OPENCL_POSTPROCESS_KERNELS_H

/* OpenCL Kernel for Zero-Copy GPU Post-Processing:
 * - 65536-entry levels_lut (pre_calc_levels: black/white level normalization)
 * - White Balance multipliers (d0, d4, d8 from final_matrix) + CLAMP16
 * - 3x3 Camera Color Matrix (proper_wb_matrix)
 * - Exact Reinhard Gamut Compression (Rec709 luma weights, exact matching raw_processing.c)
 * - AgX Chroma Compression & Inversion (agx_compressed_matrix & agx_inverse)
 * - 65536-entry Composed Transfer Function & Contrast S-Curve LUT (pre_calc_curve_r[pre_calc_gamma])
 * - High-frequency 2D edge sharpening
 * - Direct 8-bit RGB888 Display Packing (shift by 8) or 16-bit for Export
 */

static const char *s_opencl_postprocess_source =
"#define CLAMP16(v) ((v) < 0.0f ? 0.0f : ((v) > 65535.0f ? 65535.0f : (v)))\n"
"\n"
"inline float ocl_reinhard(float x) { return (x < 0.0f) ? x : (x / (1.0f + x)); }\n"
"inline float ocl_reinhard_color(float x) { return (x < 0.5f) ? x : (ocl_reinhard((x - 0.5f) / 0.5f) * 0.5f + 0.5f); }\n"
"inline float ocl_reinhard_blue(float x) { return (x < 0.7f) ? x : (ocl_reinhard((x - 0.7f) / 0.3f) * 0.3f + 0.7f); }\n"
"\n"
"__kernel void k_postprocess_frame(\n"
"    __global const ushort *in_rgb,       /* [H, W, 3] from debayer (16-bit sensor scale) */\n"
"    __global uchar *out_rgb8,            /* [H, W, 3] 8-bit display output (if != NULL) */\n"
"    __global ushort *out_rgb16,          /* [H, W, 3] 16-bit export output (if != NULL) */\n"
"    int width,\n"
"    int height,\n"
"    __constant float *wb_mat,            /* 3x3 camera matrix (proper_wb_matrix) */\n"
"    float d0, float d4, float d8,        /* Diagonal WB multipliers */\n"
"    __global const ushort *levels_lut,   /* 65536-entry pre_calc_levels LUT */\n"
"    __global const ushort *gamma_lut,    /* 65536-entry composed gamma + contrast LUT */\n"
"    float sharpen_strength,              /* 0.0 to 1.0 (1.0 = 100%) */\n"
"    float y_r, float y_g, float y_b,     /* Gamut compression luma weights */\n"
"    int agx                              /* AgX mode flag */\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int idx = (y * width + x) * 3;\n"
"    ushort raw_r = in_rgb[idx + 0];\n"
"    ushort raw_g = in_rgb[idx + 1];\n"
"    ushort raw_b = in_rgb[idx + 2];\n"
"\n"
"    /* 1. Black/White level normalization via pre_calc_levels */\n"
"    float r_norm = (levels_lut != 0) ? (float)levels_lut[raw_r] : (float)raw_r;\n"
"    float g_norm = (levels_lut != 0) ? (float)levels_lut[raw_g] : (float)raw_g;\n"
"    float b_norm = (levels_lut != 0) ? (float)levels_lut[raw_b] : (float)raw_b;\n"
"\n"
"    /* 2. White balance multipliers & LIMIT16 clamp */\n"
"    float pix0 = CLAMP16(r_norm * d0);\n"
"    float pix1 = CLAMP16(g_norm * d4);\n"
"    float pix2 = CLAMP16(b_norm * d8);\n"
"\n"
"    /* 3. Camera color matrix */\n"
"    float res0 = pix0 * wb_mat[0] + pix1 * wb_mat[1] + pix2 * wb_mat[2];\n"
"    float res1 = pix0 * wb_mat[3] + pix1 * wb_mat[4] + pix2 * wb_mat[5];\n"
"    float res2 = pix0 * wb_mat[6] + pix1 * wb_mat[7] + pix2 * wb_mat[8];\n"
"\n"
"    /* 4. Gamut compression (identical to raw_processing.c) */\n"
"    float Y = y_r * res0 + y_g * res1 + y_b * res2;\n"
"    if (Y > 0.0f) {\n"
"        float min_ch = fmin(fmin(res0, res1), res2);\n"
"        float tm0 = ocl_reinhard_color((Y - res0) / Y);\n"
"        float tm1 = ocl_reinhard_blue((Y - res1) / Y);\n"
"        float tm2 = ocl_reinhard_blue((Y - res2) / Y);\n"
"        float r2_0 = -(tm0 * Y) + Y;\n"
"        float r2_1 = -(tm1 * Y) + Y;\n"
"        float r2_2 = -(tm2 * Y) + Y;\n"
"        float min_r2 = fmin(fmin(r2_0, r2_1), r2_2);\n"
"        float denom = Y - min_ch;\n"
"        float desat = (denom > 1e-4f) ? ((Y - min_r2) / denom) : 1.0f;\n"
"        res0 = (res0 - Y) * desat + Y;\n"
"        res1 = (res1 - Y) * desat + Y;\n"
"        res2 = (res2 - Y) * desat + Y;\n"
"    }\n"
"\n"
"    /* 5. AgX Chroma Compression */\n"
"    if (agx) {\n"
"        res0 = fmax(res0, 0.0f);\n"
"        res1 = fmax(res1, 0.0f);\n"
"        res2 = fmax(res2, 0.0f);\n"
"        float a0 = res0 * 0.84247906f + res1 * 0.07843360f + res2 * 0.07922375f;\n"
"        float a1 = res0 * 0.04232824f + res1 * 0.87846864f + res2 * 0.07916613f;\n"
"        float a2 = res0 * 0.04237565f + res1 * 0.07843360f + res2 * 0.87914297f;\n"
"        res0 = a0; res1 = a1; res2 = a2;\n"
"    }\n"
"\n"
"    /* 6. Composed Gamma & Contrast Transfer Curve mapping */\n"
"    int ir = clamp((int)res0, 0, 65535);\n"
"    int ig = clamp((int)res1, 0, 65535);\n"
"    int ib = clamp((int)res2, 0, 65535);\n"
"    float c0 = (gamma_lut != 0) ? (float)gamma_lut[ir] : (float)ir;\n"
"    float c1 = (gamma_lut != 0) ? (float)gamma_lut[ig] : (float)ig;\n"
"    float c2 = (gamma_lut != 0) ? (float)gamma_lut[ib] : (float)ib;\n"
"\n"
"    /* 7. AgX Chroma Decompression (Inverse) */\n"
"    float out0, out1, out2;\n"
"    if (agx) {\n"
"        out0 = CLAMP16(c0 *  1.19687900f + c1 * -0.09802088f + c2 * -0.09902975f);\n"
"        out1 = CLAMP16(c0 * -0.05289685f + c1 *  1.15190310f + c2 * -0.09896118f);\n"
"        out2 = CLAMP16(c0 * -0.05297163f + c1 * -0.09804345f + c2 *  1.15107370f);\n"
"    } else {\n"
"        out0 = c0; out1 = c1; out2 = c2;\n"
"    }\n"
"\n"
"    /* 8. 2D Luma Sharpening */\n"
"    if (sharpen_strength > 0.005f && x > 0 && x < width - 1 && y > 0 && y < height - 1) {\n"
"        float k = pown(sharpen_strength, 1) * 0.35f;\n"
"        int idx_top = ((y - 1) * width + x) * 3;\n"
"        int idx_bot = ((y + 1) * width + x) * 3;\n"
"        int idx_lft = (y * width + (x - 1)) * 3;\n"
"        int idx_rgt = (y * width + (x + 1)) * 3;\n"
"\n"
"        float Y_t = 0.299f * (float)levels_lut[in_rgb[idx_top]]   + 0.587f * (float)levels_lut[in_rgb[idx_top+1]] + 0.114f * (float)levels_lut[in_rgb[idx_top+2]];\n"
"        float Y_b = 0.299f * (float)levels_lut[in_rgb[idx_bot]]   + 0.587f * (float)levels_lut[in_rgb[idx_bot+1]] + 0.114f * (float)levels_lut[in_rgb[idx_bot+2]];\n"
"        float Y_l = 0.299f * (float)levels_lut[in_rgb[idx_lft]]   + 0.587f * (float)levels_lut[in_rgb[idx_lft+1]] + 0.114f * (float)levels_lut[in_rgb[idx_lft+2]];\n"
"        float Y_r = 0.299f * (float)levels_lut[in_rgb[idx_rgt]]   + 0.587f * (float)levels_lut[in_rgb[idx_rgt+1]] + 0.114f * (float)levels_lut[in_rgb[idx_rgt+2]];\n"
"        float Y_c = 0.299f * r_norm + 0.587f * g_norm + 0.114f * b_norm;\n"
"\n"
"        float lap = 4.0f * Y_c - (Y_t + Y_b + Y_l + Y_r);\n"
"        float boost = lap * (out0 / (Y_c + 1.0f)) * k;\n"
"        out0 = CLAMP16(out0 + boost);\n"
"        out1 = CLAMP16(out1 + boost);\n"
"        out2 = CLAMP16(out2 + boost);\n"
"    }\n"
"\n"
"    /* 9. Output packing */\n"
"    if (out_rgb8 != 0) {\n"
"        out_rgb8[idx + 0] = (uchar)((ushort)out0 >> 8);\n"
"        out_rgb8[idx + 1] = (uchar)((ushort)out1 >> 8);\n"
"        out_rgb8[idx + 2] = (uchar)((ushort)out2 >> 8);\n"
"    }\n"
"    if (out_rgb16 != 0) {\n"
"        out_rgb16[idx + 0] = (ushort)out0;\n"
"        out_rgb16[idx + 1] = (ushort)out1;\n"
"        out_rgb16[idx + 2] = (ushort)out2;\n"
"    }\n"
"}\n";

#endif /* OPENCL_POSTPROCESS_KERNELS_H */
