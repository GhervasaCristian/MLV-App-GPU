#ifndef OPENCL_RCD_KERNELS_H
#define OPENCL_RCD_KERNELS_H

static const char* s_rcd_kernel_src =
"#define BAYER_R 0\n"
"#define BAYER_G 1\n"
"#define BAYER_B 2\n"
"\n"
"inline int rcd_get_color(int x, int y, int cfa) {\n"
"    int r = y & 1;\n"
"    int c = x & 1;\n"
"    if (cfa == 0x01000201) { /* GBRG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_B) : ((c == 0) ? BAYER_R : BAYER_G);\n"
"    } else if (cfa == 0x00010102) { /* BGGR */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_B : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_R);\n"
"    } else if (cfa == 0x01020001) { /* GRBG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_R) : ((c == 0) ? BAYER_B : BAYER_G);\n"
"    } else { /* RGGB 0x02010100 or default */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_R : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_B);\n"
"    }\n"
"}\n"
"\n"
"inline float sample_bayer(__global const ushort* raw, int x, int y, int w, int h) {\n"
"    x = clamp(x, 0, w - 1);\n"
"    y = clamp(y, 0, h - 1);\n"
"    return (float)raw[y * w + x];\n"
"}\n"
"\n"
"inline float sample_buf(__global const float* buf, int x, int y, int w, int h) {\n"
"    x = clamp(x, 0, w - 1);\n"
"    y = clamp(y, 0, h - 1);\n"
"    return buf[y * w + x];\n"
"}\n"
"\n"
"inline void swap_val(float* a, float* b) {\n"
"    if (*a > *b) {\n"
"        float t = *a;\n"
"        *a = *b;\n"
"        *b = t;\n"
"    }\n"
"}\n"
"\n"
"/* Fast 9-element sorting network median (19 compare-and-swaps, zero branch divergence) */\n"
"inline float opt_median9(float p[9]) {\n"
"    swap_val(&p[1], &p[2]); swap_val(&p[4], &p[5]); swap_val(&p[7], &p[8]);\n"
"    swap_val(&p[0], &p[1]); swap_val(&p[3], &p[4]); swap_val(&p[6], &p[7]);\n"
"    swap_val(&p[1], &p[2]); swap_val(&p[4], &p[5]); swap_val(&p[7], &p[8]);\n"
"    swap_val(&p[0], &p[3]); swap_val(&p[5], &p[8]); swap_val(&p[4], &p[7]);\n"
"    swap_val(&p[3], &p[6]); swap_val(&p[1], &p[4]); swap_val(&p[2], &p[5]);\n"
"    swap_val(&p[4], &p[7]); swap_val(&p[4], &p[2]); swap_val(&p[6], &p[4]);\n"
"    swap_val(&p[4], &p[2]);\n"
"    return p[4];\n"
"}\n"
"\n"
"/* Pass 1: Multi-Directional Laplacian Green Reconstruction */\n"
"__kernel void k_rcd_step1_green(\n"
"    __global const ushort* raw,\n"
"    __global float* green_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int color = rcd_get_color(x, y, cfa);\n"
"    float c0 = sample_bayer(raw, x, y, width, height);\n"
"    if (color == BAYER_G) {\n"
"        green_out[y * width + x] = c0;\n"
"        return;\n"
"    }\n"
"\n"
"    /* Same-channel Green neighbors */\n"
"    float gl = sample_bayer(raw, x - 1, y, width, height);\n"
"    float gr = sample_bayer(raw, x + 1, y, width, height);\n"
"    float gu = sample_bayer(raw, x, y - 1, width, height);\n"
"    float gd = sample_bayer(raw, x, y + 1, width, height);\n"
"\n"
"    /* Same-channel Red/Blue neighbors for 2nd-order Laplacian */\n"
"    float c_l2 = sample_bayer(raw, x - 2, y, width, height);\n"
"    float c_r2 = sample_bayer(raw, x + 2, y, width, height);\n"
"    float c_u2 = sample_bayer(raw, x, y - 2, width, height);\n"
"    float c_d2 = sample_bayer(raw, x, y + 2, width, height);\n"
"\n"
"    /* 5-tap same-channel directional gradients */\n"
"    float grad_h = fabs(gl - gr) + fabs(2.0f * c0 - c_l2 - c_r2);\n"
"    float grad_v = fabs(gu - gd) + fabs(2.0f * c0 - c_u2 - c_d2);\n"
"\n"
"    /* 2nd-order Laplacian Green estimates */\n"
"    float est_h = clamp(0.5f * (gl + gr) + 0.25f * (2.0f * c0 - c_l2 - c_r2), 0.0f, 65535.0f);\n"
"    float est_v = clamp(0.5f * (gu + gd) + 0.25f * (2.0f * c0 - c_u2 - c_d2), 0.0f, 65535.0f);\n"
"\n"
"    /* 4th-power edge-locking directional weights */\n"
"    float gh1 = grad_h + 1.0f;\n"
"    float gv1 = grad_v + 1.0f;\n"
"    float gh2 = gh1 * gh1;\n"
"    float gv2 = gv1 * gv1;\n"
"    float w_h = gv2 * gv2;\n"
"    float w_v = gh2 * gh2;\n"
"\n"
"    green_out[y * width + x] = (w_h * est_h + w_v * est_v) / (w_h + w_v);\n"
"}\n"
"\n"
"/* Pass 2: Directional Chromatic Difference Fields (Diff_R = R - G, Diff_B = B - G) */\n"
"__kernel void k_rcd_step2_chroma(\n"
"    __global const ushort* raw,\n"
"    __global const float* green,\n"
"    __global float* diff_r_out,\n"
"    __global float* diff_b_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int color = rcd_get_color(x, y, cfa);\n"
"    float g0 = green[y * width + x];\n"
"    float dr = 0.0f, db = 0.0f;\n"
"\n"
"    if (color == BAYER_R) {\n"
"        dr = (float)raw[y * width + x] - g0;\n"
"        /* Diagonal Blue estimation */\n"
"        float db_nw = sample_bayer(raw, x - 1, y - 1, width, height) - sample_buf(green, x - 1, y - 1, width, height);\n"
"        float db_ne = sample_bayer(raw, x + 1, y - 1, width, height) - sample_buf(green, x + 1, y - 1, width, height);\n"
"        float db_sw = sample_bayer(raw, x - 1, y + 1, width, height) - sample_buf(green, x - 1, y + 1, width, height);\n"
"        float db_se = sample_bayer(raw, x + 1, y + 1, width, height) - sample_buf(green, x + 1, y + 1, width, height);\n"
"\n"
"        float g_nw = sample_buf(green, x - 1, y - 1, width, height);\n"
"        float g_ne = sample_buf(green, x + 1, y - 1, width, height);\n"
"        float g_sw = sample_buf(green, x - 1, y + 1, width, height);\n"
"        float g_se = sample_buf(green, x + 1, y + 1, width, height);\n"
"\n"
"        float grad_diag1 = fabs(db_nw - db_se) + fabs(g_nw - g_se);\n"
"        float grad_diag2 = fabs(db_ne - db_sw) + fabs(g_ne - g_sw);\n"
"        float d1 = grad_diag1 + 1.0f;\n"
"        float d2 = grad_diag2 + 1.0f;\n"
"        float w1 = d2 * d2;\n"
"        float w2 = d1 * d1;\n"
"\n"
"        db = (w1 * 0.5f * (db_nw + db_se) + w2 * 0.5f * (db_ne + db_sw)) / (w1 + w2);\n"
"    } else if (color == BAYER_B) {\n"
"        db = (float)raw[y * width + x] - g0;\n"
"        /* Diagonal Red estimation */\n"
"        float dr_nw = sample_bayer(raw, x - 1, y - 1, width, height) - sample_buf(green, x - 1, y - 1, width, height);\n"
"        float dr_ne = sample_bayer(raw, x + 1, y - 1, width, height) - sample_buf(green, x + 1, y - 1, width, height);\n"
"        float dr_sw = sample_bayer(raw, x - 1, y + 1, width, height) - sample_buf(green, x - 1, y + 1, width, height);\n"
"        float dr_se = sample_bayer(raw, x + 1, y + 1, width, height) - sample_buf(green, x + 1, y + 1, width, height);\n"
"\n"
"        float g_nw = sample_buf(green, x - 1, y - 1, width, height);\n"
"        float g_ne = sample_buf(green, x + 1, y - 1, width, height);\n"
"        float g_sw = sample_buf(green, x - 1, y + 1, width, height);\n"
"        float g_se = sample_buf(green, x + 1, y + 1, width, height);\n"
"\n"
"        float grad_diag1 = fabs(dr_nw - dr_se) + fabs(g_nw - g_se);\n"
"        float grad_diag2 = fabs(dr_ne - dr_sw) + fabs(g_ne - g_sw);\n"
"        float d1 = grad_diag1 + 1.0f;\n"
"        float d2 = grad_diag2 + 1.0f;\n"
"        float w1 = d2 * d2;\n"
"        float w2 = d1 * d1;\n"
"\n"
"        dr = (w1 * 0.5f * (dr_nw + dr_se) + w2 * 0.5f * (dr_ne + dr_sw)) / (w1 + w2);\n"
"    } else { /* BAYER_G */\n"
"        float g_l = sample_buf(green, x - 1, y, width, height);\n"
"        float g_r = sample_buf(green, x + 1, y, width, height);\n"
"        float g_u = sample_buf(green, x, y - 1, width, height);\n"
"        float g_d = sample_buf(green, x, y + 1, width, height);\n"
"\n"
"        float wl = 1.0f / (fabs(g0 - g_l) + 1.0f);\n"
"        float wr = 1.0f / (fabs(g0 - g_r) + 1.0f);\n"
"        float wu = 1.0f / (fabs(g0 - g_u) + 1.0f);\n"
"        float wd = 1.0f / (fabs(g0 - g_d) + 1.0f);\n"
"\n"
"        int c_left = rcd_get_color(x - 1, y, cfa);\n"
"        if (c_left == BAYER_R || rcd_get_color(x + 1, y, cfa) == BAYER_R) {\n"
"            /* Red is horizontal, Blue is vertical */\n"
"            float dr_l = sample_bayer(raw, x - 1, y, width, height) - g_l;\n"
"            float dr_r = sample_bayer(raw, x + 1, y, width, height) - g_r;\n"
"            float db_u = sample_bayer(raw, x, y - 1, width, height) - g_u;\n"
"            float db_d = sample_bayer(raw, x, y + 1, width, height) - g_d;\n"
"            dr = (wl * dr_l + wr * dr_r) / (wl + wr);\n"
"            db = (wu * db_u + wd * db_d) / (wu + wd);\n"
"        } else {\n"
"            /* Blue is horizontal, Red is vertical */\n"
"            float db_l = sample_bayer(raw, x - 1, y, width, height) - g_l;\n"
"            float db_r = sample_bayer(raw, x + 1, y, width, height) - g_r;\n"
"            float dr_u = sample_bayer(raw, x, y - 1, width, height) - g_u;\n"
"            float dr_d = sample_bayer(raw, x, y + 1, width, height) - g_d;\n"
"            db = (wl * db_l + wr * db_r) / (wl + wr);\n"
"            dr = (wu * dr_u + wd * dr_d) / (wu + wd);\n"
"        }\n"
"    }\n"
"\n"
"    int idx = y * width + x;\n"
"    diff_r_out[idx] = dr;\n"
"    diff_b_out[idx] = db;\n"
"}\n"
"\n"
"/* Pass 3: 3x3 Anti-Zipper Median Filter & Full RGB Synthesis */\n"
"__kernel void k_rcd_step3_rgb(\n"
"    __global const float* green,\n"
"    __global const float* diff_r,\n"
"    __global const float* diff_b,\n"
"    __global ushort* rgb_out,\n"
"    int width, int height\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    float g_val = green[y * width + x];\n"
"\n"
"    /* 3x3 Median filter on Diff_R to completely eliminate high-contrast pixel artifacts */\n"
"    float pr[9];\n"
"    pr[0] = sample_buf(diff_r, x - 1, y - 1, width, height);\n"
"    pr[1] = sample_buf(diff_r, x,     y - 1, width, height);\n"
"    pr[2] = sample_buf(diff_r, x + 1, y - 1, width, height);\n"
"    pr[3] = sample_buf(diff_r, x - 1, y,     width, height);\n"
"    pr[4] = sample_buf(diff_r, x,     y,     width, height);\n"
"    pr[5] = sample_buf(diff_r, x + 1, y,     width, height);\n"
"    pr[6] = sample_buf(diff_r, x - 1, y + 1, width, height);\n"
"    pr[7] = sample_buf(diff_r, x,     y + 1, width, height);\n"
"    pr[8] = sample_buf(diff_r, x + 1, y + 1, width, height);\n"
"    float med_r = opt_median9(pr);\n"
"\n"
"    /* 3x3 Median filter on Diff_B */\n"
"    float pb[9];\n"
"    pb[0] = sample_buf(diff_b, x - 1, y - 1, width, height);\n"
"    pb[1] = sample_buf(diff_b, x,     y - 1, width, height);\n"
"    pb[2] = sample_buf(diff_b, x + 1, y - 1, width, height);\n"
"    pb[3] = sample_buf(diff_b, x - 1, y,     width, height);\n"
"    pb[4] = sample_buf(diff_b, x,     y,     width, height);\n"
"    pb[5] = sample_buf(diff_b, x + 1, y,     width, height);\n"
"    pb[6] = sample_buf(diff_b, x - 1, y + 1, width, height);\n"
"    pb[7] = sample_buf(diff_b, x,     y + 1, width, height);\n"
"    pb[8] = sample_buf(diff_b, x + 1, y + 1, width, height);\n"
"    float med_b = opt_median9(pb);\n"
"\n"
"    /* Final razor-sharp RGB synthesis */\n"
"    int out_idx = (y * width + x) * 3;\n"
"    rgb_out[out_idx + 0] = (ushort)clamp(g_val + med_r, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 1] = (ushort)clamp(g_val,         0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 2] = (ushort)clamp(g_val + med_b, 0.0f, 65535.0f);\n"
"}\n";

#endif /* OPENCL_RCD_KERNELS_H */
