#ifndef OPENCL_RCDV2_KERNELS_H
#define OPENCL_RCDV2_KERNELS_H

/*
 * Pure GPU OpenCL Port of Luis Sanz Rodriguez's Ratio Corrected Demosaicing (RCD v2.3)
 * Exactly mirrors RawTherapee / librtprocess rcd.cc
 */
static const char* s_rcdv2_kernel_src =
"#define BAYER_R 0\n"
"#define BAYER_G 1\n"
"#define BAYER_B 2\n"
"#define SQR(x) ((x) * (x))\n"
"\n"
"inline int rcdv2_get_color(int x, int y, int cfa) {\n"
"    int r = y & 1;\n"
"    int c = x & 1;\n"
"    if (cfa == 0x01000201) { /* GBRG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_B) : ((c == 0) ? BAYER_R : BAYER_G);\n"
"    } else if (cfa == 0x00010102) { /* BGGR */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_B : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_R);\n"
"    } else if (cfa == 0x01020001) { /* GRBG */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_G : BAYER_R) : ((c == 0) ? BAYER_B : BAYER_G);\n"
"    } else { /* RGGB 0x02010100 or default */\n"
"        return (r == 0) ? ((c == 0) ? BAYER_R : BAYER_G) : ((c == 0) ? BAYER_G : BAYER_B);\n"
"    }\n"
"}\n"
"\n"
"inline float v2_sample_raw(__global const ushort* raw, int x, int y, int w, int h) {\n"
"    x = clamp(x, 0, w - 1);\n"
"    y = clamp(y, 0, h - 1);\n"
"    return (float)raw[y * w + x];\n"
"}\n"
"\n"
"inline float v2_sample_buf(__global const float* buf, int x, int y, int w, int h) {\n"
"    x = clamp(x, 0, w - 1);\n"
"    y = clamp(y, 0, h - 1);\n"
"    return buf[y * w + x];\n"
"}\n"
"\n"
"/* Pass 1: Multispectral LPF at R/B sites & 3-tap smoothed VH discrimination */\n"
"__kernel void k_rcdv2_step1_lpf_vh(\n"
"    __global const ushort* raw,\n"
"    __global float* lpf_out,\n"
"    __global float* vh_dir_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int idx = y * width + x;\n"
"    int col_type = rcdv2_get_color(x, y, cfa);\n"
"\n"
"    /* 1. Low pass filter at R and B sites */\n"
"    if (col_type != BAYER_G) {\n"
"        float c0 = v2_sample_raw(raw, x, y, width, height);\n"
"        float g_card = v2_sample_raw(raw, x, y - 1, width, height) +\n"
"                       v2_sample_raw(raw, x, y + 1, width, height) +\n"
"                       v2_sample_raw(raw, x - 1, y, width, height) +\n"
"                       v2_sample_raw(raw, x + 1, y, width, height);\n"
"        float diag = v2_sample_raw(raw, x - 1, y - 1, width, height) +\n"
"                     v2_sample_raw(raw, x + 1, y - 1, width, height) +\n"
"                     v2_sample_raw(raw, x - 1, y + 1, width, height) +\n"
"                     v2_sample_raw(raw, x + 1, y + 1, width, height);\n"
"        lpf_out[idx] = c0 + 0.5f * g_card + 0.25f * diag;\n"
"    } else {\n"
"        lpf_out[idx] = 0.0f;\n"
"    }\n"
"\n"
"    /* 2. Vertical and Horizontal High Pass Filters & 3-tap statistical smoothing */\n"
"    float v_stat = 0.0f;\n"
"    for (int dy = -1; dy <= 1; dy++) {\n"
"        int ry = y + dy;\n"
"        float diff_v = (v2_sample_raw(raw, x, ry - 3, width, height) - v2_sample_raw(raw, x, ry - 1, width, height) - v2_sample_raw(raw, x, ry + 1, width, height) + v2_sample_raw(raw, x, ry + 3, width, height))\n"
"                     - 3.0f * (v2_sample_raw(raw, x, ry - 2, width, height) + v2_sample_raw(raw, x, ry + 2, width, height))\n"
"                     + 6.0f * v2_sample_raw(raw, x, ry, width, height);\n"
"        v_stat += SQR(diff_v);\n"
"    }\n"
"\n"
"    float h_stat = 0.0f;\n"
"    for (int dx = -1; dx <= 1; dx++) {\n"
"        int rx = x + dx;\n"
"        float diff_h = (v2_sample_raw(raw, rx - 3, y, width, height) - v2_sample_raw(raw, rx - 1, y, width, height) - v2_sample_raw(raw, rx + 1, y, width, height) + v2_sample_raw(raw, rx + 3, y, width, height))\n"
"                     - 3.0f * (v2_sample_raw(raw, rx - 2, y, width, height) + v2_sample_raw(raw, rx + 2, y, width, height))\n"
"                     + 6.0f * v2_sample_raw(raw, rx, y, width, height);\n"
"        h_stat += SQR(diff_h);\n"
"    }\n"
"\n"
"    v_stat = fmax(1e-10f, v_stat);\n"
"    h_stat = fmax(1e-10f, h_stat);\n"
"    vh_dir_out[idx] = v_stat / (v_stat + h_stat);\n"
"}\n"
"\n"
"/* Pass 2: Ratio-Corrected Green Interpolation */\n"
"__kernel void k_rcdv2_step2_green(\n"
"    __global const ushort* raw,\n"
"    __global const float* lpf,\n"
"    __global const float* vh_dir,\n"
"    __global float* green_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int idx = y * width + x;\n"
"    int col_type = rcdv2_get_color(x, y, cfa);\n"
"\n"
"    if (col_type == BAYER_G) {\n"
"        green_out[idx] = (float)raw[idx];\n"
"        return;\n"
"    }\n"
"\n"
"    float cfai = (float)raw[idx];\n"
"    float eps = 1e-4f;\n"
"\n"
"    /* Cardinal Gradients */\n"
"    float n_grad = eps + (fabs(v2_sample_raw(raw, x, y - 1, width, height) - v2_sample_raw(raw, x, y + 1, width, height)) + fabs(cfai - v2_sample_raw(raw, x, y - 2, width, height)))\n"
"                       + (fabs(v2_sample_raw(raw, x, y - 1, width, height) - v2_sample_raw(raw, x, y - 3, width, height)) + fabs(v2_sample_raw(raw, x, y - 2, width, height) - v2_sample_raw(raw, x, y - 4, width, height)));\n"
"\n"
"    float s_grad = eps + (fabs(v2_sample_raw(raw, x, y - 1, width, height) - v2_sample_raw(raw, x, y + 1, width, height)) + fabs(cfai - v2_sample_raw(raw, x, y + 2, width, height)))\n"
"                       + (fabs(v2_sample_raw(raw, x, y + 1, width, height) - v2_sample_raw(raw, x, y + 3, width, height)) + fabs(v2_sample_raw(raw, x, y + 2, width, height) - v2_sample_raw(raw, x, y + 4, width, height)));\n"
"\n"
"    float w_grad = eps + (fabs(v2_sample_raw(raw, x - 1, y, width, height) - v2_sample_raw(raw, x + 1, y, width, height)) + fabs(cfai - v2_sample_raw(raw, x - 2, y, width, height)))\n"
"                       + (fabs(v2_sample_raw(raw, x - 1, y, width, height) - v2_sample_raw(raw, x - 3, y, width, height)) + fabs(v2_sample_raw(raw, x - 2, y, width, height) - v2_sample_raw(raw, x - 4, y, width, height)));\n"
"\n"
"    float e_grad = eps + (fabs(v2_sample_raw(raw, x - 1, y, width, height) - v2_sample_raw(raw, x + 1, y, width, height)) + fabs(cfai - v2_sample_raw(raw, x + 2, y, width, height)))\n"
"                       + (fabs(v2_sample_raw(raw, x + 1, y, width, height) - v2_sample_raw(raw, x + 3, y, width, height)) + fabs(v2_sample_raw(raw, x + 2, y, width, height) - v2_sample_raw(raw, x + 4, y, width, height)));\n"
"\n"
"    /* Ratio-corrected Cardinal Estimations */\n"
"    float lpfi = v2_sample_buf(lpf, x, y, width, height);\n"
"    float lpf_n = v2_sample_buf(lpf, x, y - 2, width, height);\n"
"    float lpf_s = v2_sample_buf(lpf, x, y + 2, width, height);\n"
"    float lpf_w = v2_sample_buf(lpf, x - 2, y, width, height);\n"
"    float lpf_e = v2_sample_buf(lpf, x + 2, y, width, height);\n"
"\n"
"    float n_est = v2_sample_raw(raw, x, y - 1, width, height) * (2.0f * lpfi) / (eps + lpfi + lpf_n);\n"
"    float s_est = v2_sample_raw(raw, x, y + 1, width, height) * (2.0f * lpfi) / (eps + lpfi + lpf_s);\n"
"    float w_est = v2_sample_raw(raw, x - 1, y, width, height) * (2.0f * lpfi) / (eps + lpfi + lpf_w);\n"
"    float e_est = v2_sample_raw(raw, x + 1, y, width, height) * (2.0f * lpfi) / (eps + lpfi + lpf_e);\n"
"\n"
"    /* Vertical and Horizontal Estimations */\n"
"    float v_est = (s_grad * n_est + n_grad * s_est) / (n_grad + s_grad);\n"
"    float h_est = (w_grad * e_est + e_grad * w_est) / (e_grad + w_grad);\n"
"\n"
"    /* Refined VH Discrimination */\n"
"    float vh_cen = v2_sample_buf(vh_dir, x, y, width, height);\n"
"    float vh_nbr = 0.25f * (v2_sample_buf(vh_dir, x - 1, y - 1, width, height) +\n"
"                           v2_sample_buf(vh_dir, x + 1, y - 1, width, height) +\n"
"                           v2_sample_buf(vh_dir, x - 1, y + 1, width, height) +\n"
"                           v2_sample_buf(vh_dir, x + 1, y + 1, width, height));\n"
"    float vh_disc = (fabs(0.5f - vh_cen) < fabs(0.5f - vh_nbr)) ? vh_nbr : vh_cen;\n"
"\n"
"    green_out[idx] = vh_disc * h_est + (1.0f - vh_disc) * v_est;\n"
"}\n"
"\n"
"/* Pass 3: Populate R@B and B@R using Diagonal Discrimination and Color Differences */\n"
"__kernel void k_rcdv2_step3_rb_diag(\n"
"    __global const ushort* raw,\n"
"    __global const float* green,\n"
"    __global float* red_out,\n"
"    __global float* blue_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int idx = y * width + x;\n"
"    int col_type = rcdv2_get_color(x, y, cfa);\n"
"\n"
"    if (col_type == BAYER_R) {\n"
"        red_out[idx] = (float)raw[idx];\n"
"    } else if (col_type == BAYER_B) {\n"
"        blue_out[idx] = (float)raw[idx];\n"
"    }\n"
"\n"
"    if (col_type == BAYER_G) {\n"
"        return;\n"
"    }\n"
"\n"
"    /* Diagonal High Pass Filter and P/Q Discrimination */\n"
"    float p_stat = 0.0f, q_stat = 0.0f;\n"
"    for (int d = -1; d <= 1; d++) {\n"
"        int px = x + d;\n"
"        int py = y + d;\n"
"        float diff_p = (v2_sample_raw(raw, px - 3, py - 3, width, height) - v2_sample_raw(raw, px - 1, py - 1, width, height) - v2_sample_raw(raw, px + 1, py + 1, width, height) + v2_sample_raw(raw, px + 3, py + 3, width, height))\n"
"                     - 3.0f * (v2_sample_raw(raw, px - 2, py - 2, width, height) + v2_sample_raw(raw, px + 2, py + 2, width, height))\n"
"                     + 6.0f * v2_sample_raw(raw, px, py, width, height);\n"
"        p_stat += SQR(diff_p);\n"
"\n"
"        int qx = x - d;\n"
"        int qy = y + d;\n"
"        float diff_q = (v2_sample_raw(raw, qx + 3, qy - 3, width, height) - v2_sample_raw(raw, qx + 1, qy - 1, width, height) - v2_sample_raw(raw, qx - 1, qy + 1, width, height) + v2_sample_raw(raw, qx - 3, qy + 3, width, height))\n"
"                     - 3.0f * (v2_sample_raw(raw, qx + 2, qy - 2, width, height) + v2_sample_raw(raw, qx - 2, qy + 2, width, height))\n"
"                     + 6.0f * v2_sample_raw(raw, qx, qy, width, height);\n"
"        q_stat += SQR(diff_q);\n"
"    }\n"
"\n"
"    p_stat = fmax(1e-10f, p_stat);\n"
"    q_stat = fmax(1e-10f, q_stat);\n"
"    float pq_disc = p_stat / (p_stat + q_stat);\n"
"\n"
"    float eps = 1e-4f;\n"
"    float g0 = v2_sample_buf(green, x, y, width, height);\n"
"\n"
"    float c_nw = v2_sample_raw(raw, x - 1, y - 1, width, height);\n"
"    float c_ne = v2_sample_raw(raw, x + 1, y - 1, width, height);\n"
"    float c_sw = v2_sample_raw(raw, x - 1, y + 1, width, height);\n"
"    float c_se = v2_sample_raw(raw, x + 1, y + 1, width, height);\n"
"\n"
"    float g_nw = v2_sample_buf(green, x - 1, y - 1, width, height);\n"
"    float g_ne = v2_sample_buf(green, x + 1, y - 1, width, height);\n"
"    float g_sw = v2_sample_buf(green, x - 1, y + 1, width, height);\n"
"    float g_se = v2_sample_buf(green, x + 1, y + 1, width, height);\n"
"\n"
"    float nw_grad = eps + fabs(c_nw - c_se) + fabs(c_nw - v2_sample_raw(raw, x - 3, y - 3, width, height)) + fabs(g0 - v2_sample_buf(green, x - 2, y - 2, width, height));\n"
"    float se_grad = eps + fabs(c_nw - c_se) + fabs(c_se - v2_sample_raw(raw, x + 3, y + 3, width, height)) + fabs(g0 - v2_sample_buf(green, x + 2, y + 2, width, height));\n"
"    float ne_grad = eps + fabs(c_ne - c_sw) + fabs(c_ne - v2_sample_raw(raw, x + 3, y - 3, width, height)) + fabs(g0 - v2_sample_buf(green, x + 2, y - 2, width, height));\n"
"    float sw_grad = eps + fabs(c_ne - c_sw) + fabs(c_sw - v2_sample_raw(raw, x - 3, y + 3, width, height)) + fabs(g0 - v2_sample_buf(green, x - 2, y + 2, width, height));\n"
"\n"
"    float nw_est = c_nw - g_nw;\n"
"    float se_est = c_se - g_se;\n"
"    float ne_est = c_ne - g_ne;\n"
"    float sw_est = c_sw - g_sw;\n"
"\n"
"    float p_est = (nw_grad * se_est + se_grad * nw_est) / (nw_grad + se_grad);\n"
"    float q_est = (ne_grad * sw_est + sw_grad * ne_est) / (ne_grad + sw_grad);\n"
"\n"
"    float c_interp = g0 + (pq_disc * q_est + (1.0f - pq_disc) * p_est);\n"
"\n"
"    if (col_type == BAYER_R) {\n"
"        blue_out[idx] = c_interp;\n"
"    } else {\n"
"        red_out[idx] = c_interp;\n"
"    }\n"
"}\n"
"\n"
"/* Pass 4: Populate R and B at Green Sites and Synthesize Final 16-bit RGB */\n"
"__kernel void k_rcdv2_step4_synthesis(\n"
"    __global const float* green,\n"
"    __global const float* red_in,\n"
"    __global const float* blue_in,\n"
"    __global const float* vh_dir,\n"
"    __global ushort* rgb_out,\n"
"    int width, int height, int cfa\n"
") {\n"
"    int x = get_global_id(0);\n"
"    int y = get_global_id(1);\n"
"    if (x >= width || y >= height) return;\n"
"\n"
"    int idx = y * width + x;\n"
"    int col_type = rcdv2_get_color(x, y, cfa);\n"
"    float g0 = green[idx];\n"
"    float r0, b0;\n"
"\n"
"    if (col_type != BAYER_G) {\n"
"        r0 = red_in[idx];\n"
"        b0 = blue_in[idx];\n"
"    } else {\n"
"        float eps = 1e-4f;\n"
"        float vh_cen = v2_sample_buf(vh_dir, x, y, width, height);\n"
"        float vh_nbr = 0.25f * (v2_sample_buf(vh_dir, x - 1, y - 1, width, height) +\n"
"                               v2_sample_buf(vh_dir, x + 1, y - 1, width, height) +\n"
"                               v2_sample_buf(vh_dir, x - 1, y + 1, width, height) +\n"
"                               v2_sample_buf(vh_dir, x + 1, y + 1, width, height));\n"
"        float vh_disc = (fabs(0.5f - vh_cen) < fabs(0.5f - vh_nbr)) ? vh_nbr : vh_cen;\n"
"\n"
"        float n1 = eps + fabs(g0 - v2_sample_buf(green, x, y - 2, width, height));\n"
"        float s1 = eps + fabs(g0 - v2_sample_buf(green, x, y + 2, width, height));\n"
"        float w1 = eps + fabs(g0 - v2_sample_buf(green, x - 2, y, width, height));\n"
"        float e1 = eps + fabs(g0 - v2_sample_buf(green, x + 2, y, width, height));\n"
"\n"
"        float g_n = v2_sample_buf(green, x, y - 1, width, height);\n"
"        float g_s = v2_sample_buf(green, x, y + 1, width, height);\n"
"        float g_w = v2_sample_buf(green, x - 1, y, width, height);\n"
"        float g_e = v2_sample_buf(green, x + 1, y, width, height);\n"
"\n"
"        /* Cardinal Red */\n"
"        float rn = v2_sample_buf(red_in, x, y - 1, width, height);\n"
"        float rs = v2_sample_buf(red_in, x, y + 1, width, height);\n"
"        float rw = v2_sample_buf(red_in, x - 1, y, width, height);\n"
"        float re = v2_sample_buf(red_in, x + 1, y, width, height);\n"
"\n"
"        float r_sn_abs = fabs(rn - rs);\n"
"        float r_ew_abs = fabs(rw - re);\n"
"        float r_n_grad = n1 + r_sn_abs + fabs(rn - v2_sample_buf(red_in, x, y - 3, width, height));\n"
"        float r_s_grad = s1 + r_sn_abs + fabs(rs - v2_sample_buf(red_in, x, y + 3, width, height));\n"
"        float r_w_grad = w1 + r_ew_abs + fabs(rw - v2_sample_buf(red_in, x - 3, y, width, height));\n"
"        float r_e_grad = e1 + r_ew_abs + fabs(re - v2_sample_buf(red_in, x + 3, y, width, height));\n"
"\n"
"        float r_n_est = rn - g_n;\n"
"        float r_s_est = rs - g_s;\n"
"        float r_w_est = rw - g_w;\n"
"        float r_e_est = re - g_e;\n"
"\n"
"        float r_v_est = (r_n_grad * r_s_est + r_s_grad * r_n_est) / (r_n_grad + r_s_grad);\n"
"        float r_h_est = (r_e_grad * r_w_est + r_w_grad * r_e_est) / (r_e_grad + r_w_grad);\n"
"        r0 = g0 + (vh_disc * r_h_est + (1.0f - vh_disc) * r_v_est);\n"
"\n"
"        /* Cardinal Blue */\n"
"        float bn = v2_sample_buf(blue_in, x, y - 1, width, height);\n"
"        float bs = v2_sample_buf(blue_in, x, y + 1, width, height);\n"
"        float bw = v2_sample_buf(blue_in, x - 1, y, width, height);\n"
"        float be = v2_sample_buf(blue_in, x + 1, y, width, height);\n"
"\n"
"        float b_sn_abs = fabs(bn - bs);\n"
"        float b_ew_abs = fabs(bw - be);\n"
"        float b_n_grad = n1 + b_sn_abs + fabs(bn - v2_sample_buf(blue_in, x, y - 3, width, height));\n"
"        float b_s_grad = s1 + b_sn_abs + fabs(bs - v2_sample_buf(blue_in, x, y + 3, width, height));\n"
"        float b_w_grad = w1 + b_ew_abs + fabs(bw - v2_sample_buf(blue_in, x - 3, y, width, height));\n"
"        float b_e_grad = e1 + b_ew_abs + fabs(be - v2_sample_buf(blue_in, x + 3, y, width, height));\n"
"\n"
"        float b_n_est = bn - g_n;\n"
"        float b_s_est = bs - g_s;\n"
"        float b_w_est = bw - g_w;\n"
"        float b_e_est = be - g_e;\n"
"\n"
"        float b_v_est = (b_n_grad * b_s_est + b_s_grad * b_n_est) / (b_n_grad + b_s_grad);\n"
"        float b_h_est = (b_e_grad * b_w_est + b_w_grad * b_e_est) / (b_e_grad + b_w_grad);\n"
"        b0 = g0 + (vh_disc * b_h_est + (1.0f - vh_disc) * b_v_est);\n"
"    }\n"
"\n"
"    int out_idx = idx * 3;\n"
"    rgb_out[out_idx + 0] = (ushort)clamp(r0, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 1] = (ushort)clamp(g0, 0.0f, 65535.0f);\n"
"    rgb_out[out_idx + 2] = (ushort)clamp(b0, 0.0f, 65535.0f);\n"
"}\n";

#endif /* OPENCL_RCDV2_KERNELS_H */
